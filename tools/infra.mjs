// Create or update the site's CloudFormation stacks through change sets.
//
//   node tools/infra.mjs plan  [pitches] [site] [delivery]   print the change sets, execute nothing
//   node tools/infra.mjs apply [pitches] [site] [delivery]   execute them, in that order
//
// With no stack named: site and delivery, and pitches once it exists with
// "pitchesStack": true. Name `pitches` to create it. A plan never leaves anything
// behind: its change set is deleted once printed, and a stack that does not exist yet is
// planned from its template alone (a change set for it would park an empty stack in
// REVIEW_IN_PROGRESS).
//
// Run as the cloud-engineer identity in us-east-1. The site stack owns the
// certificate (validated through its own record in the thingelstad.xyz zone),
// the private bucket, the distribution (behind the shared edge web ACL), the
// A and AAAA alias records, the access log and the bucket for the functions'
// code. Once the pitches stack is there it also runs the pitch pages function
// (backend/pages, a Lambda Web Function behind /p/, /e/ and /og/): its package is
// tools/pages-bundle.mjs, uploaded to the code bucket under its hash. The delivery
// stack owns the GitHub OIDC role that publishes main. With "reelRenderer": true in
// infra/deployment.json the site stack also runs the highlight reel function
// (backend/reels, docs/REEL.md, docs/REEL-RUNBOOK.md): its package and ffmpeg layer
// are tools/reels-bundle.mjs's, uploaded to the code bucket under their hashes, and
// the pitches stack is given its ARN to invoke. With "pitchesStack": true the pitches
// stack (infra/pitches.json, throwing-wood-pitches) runs the api function
// throwing-wood-api (backend/api, docs/PITCH-SERVER.md, backend/api/API.md) with its
// function URL, its role, the push secret (generated by Secrets Manager, never read
// here), its own table and its own private games bucket: its package is
// tools/api-bundle.mjs's, uploaded to the site's code bucket under its hash. The site
// stack sends /api/* to it and points the pitch pages and the reel function at its
// table, and the delivery role may update its code. Apply pitches, then site, then
// delivery. Each apply rewrites infra/deployment.json from the live stack outputs.
// Infrastructure never changes through the delivery role. (The old WebSocket rooms
// stack was deleted on 2026-11-21: docs/PITCH-SERVER.md section 12.)
import {
  CloudFormationClient,
  CreateChangeSetCommand,
  DeleteChangeSetCommand,
  DescribeChangeSetCommand,
  DescribeStacksCommand,
  ExecuteChangeSetCommand,
  waitUntilChangeSetCreateComplete,
  waitUntilStackCreateComplete,
  waitUntilStackUpdateComplete,
} from "@aws-sdk/client-cloudformation";
import { S3Client, PutObjectCommand } from "@aws-sdk/client-s3";
import { STSClient, GetCallerIdentityCommand } from "@aws-sdk/client-sts";
import fs from "node:fs/promises";
import { bundleApi } from "./api-bundle.mjs";
import { bundlePages } from "./pages-bundle.mjs";
import {
  bundleReels,
  ffmpegLayer,
  reelEngines as reelEnginesOf,
} from "./reels-bundle.mjs";
import { syncSiteTemplate } from "./site-template.mjs";

const [mode, ...named] = process.argv.slice(2);
const STACKS = ["pitches", "site", "delivery"];
if (
  !["plan", "apply"].includes(mode) ||
  named.some((name) => !STACKS.includes(name))
)
  throw new Error(
    "Usage: node tools/infra.mjs plan|apply [pitches] [site] [delivery]",
  );
const config = JSON.parse(await fs.readFile("infra/deployment.json", "utf8"));
const settings = { region: config.region, maxAttempts: 5 };
const identity = await new STSClient(settings).send(
  new GetCallerIdentityCommand({}),
);
if (identity.Account !== config.account)
  throw new Error(`Unexpected AWS account ${identity.Account}`);
console.log(`Identity ${identity.Arn}`);
const cfn = new CloudFormationClient(settings);
// Every stack's tags; a stack may override some (the pitches stack's Project is
// throwing-wood, the old stacks keep theirs).
const tagsFor = (file) =>
  Object.entries({
    ...config.stackTags,
    ...(config.stackTagOverrides?.[file] || {}),
  }).map(([Key, Value]) => ({ Key, Value }));

if (await syncSiteTemplate())
  console.log(
    "Wrote the viewer request function and the CSP into infra/site.json",
  );

async function stack(name) {
  try {
    const { Stacks } = await cfn.send(
      new DescribeStacksCommand({ StackName: name }),
    );
    // A CREATE change set left by `plan` parks a new stack in
    // REVIEW_IN_PROGRESS; it still takes a CREATE change set.
    if (Stacks[0].StackStatus === "REVIEW_IN_PROGRESS") return undefined;
    return Stacks[0];
  } catch (error) {
    if (/does not exist/.test(error.message)) return undefined;
    throw error;
  }
}
const outputs = (s) =>
  Object.fromEntries(
    (s?.Outputs || []).map((o) => [o.OutputKey, o.OutputValue]),
  );

async function converge(name, file, parameters = {}, capabilities = []) {
  const existing = await stack(name);
  const type = existing ? "UPDATE" : "CREATE";
  const TemplateBody = await fs.readFile(`infra/${file}.json`, "utf8");
  if (mode === "plan" && !existing) {
    // No change set: one for a stack that does not exist yet would leave it behind.
    console.log(`${name} (CREATE, from the template; nothing sent):`);
    for (const [id, r] of Object.entries(JSON.parse(TemplateBody).Resources))
      console.log(
        `  Add ${id} ${r.Type}${r.Condition ? ` (if ${r.Condition})` : ""}`,
      );
    return existing;
  }
  const ChangeSetName = `${mode}-${Date.now()}`;
  await cfn.send(
    new CreateChangeSetCommand({
      StackName: name,
      ChangeSetName,
      ChangeSetType: type,
      TemplateBody,
      Parameters: Object.entries(parameters).map(
        ([ParameterKey, ParameterValue]) => ({ ParameterKey, ParameterValue }),
      ),
      Capabilities: capabilities,
      Tags: tagsFor(file),
    }),
  );
  try {
    await waitUntilChangeSetCreateComplete(
      { client: cfn, maxWaitTime: 300 },
      { StackName: name, ChangeSetName },
    );
  } catch (error) {
    const { StatusReason } = await cfn.send(
      new DescribeChangeSetCommand({ StackName: name, ChangeSetName }),
    );
    if (
      /didn't contain changes|No updates are to be performed/.test(
        StatusReason || "",
      )
    ) {
      console.log(`${name}: no changes`);
      await cfn.send(
        new DeleteChangeSetCommand({ StackName: name, ChangeSetName }),
      );
      return existing;
    }
    throw new Error(`${name}: ${StatusReason || error.message}`, {
      cause: error,
    });
  }
  const { Changes } = await cfn.send(
    new DescribeChangeSetCommand({ StackName: name, ChangeSetName }),
  );
  console.log(`${name} (${type}):`);
  for (const c of Changes)
    console.log(
      `  ${c.ResourceChange.Action} ${c.ResourceChange.LogicalResourceId} ${c.ResourceChange.ResourceType}${c.ResourceChange.Replacement === "True" ? " (REPLACEMENT)" : ""}`,
    );
  if (mode === "plan") {
    await cfn.send(
      new DeleteChangeSetCommand({ StackName: name, ChangeSetName }),
    );
    return existing;
  }
  await cfn.send(
    new ExecuteChangeSetCommand({ StackName: name, ChangeSetName }),
  );
  const wait =
    type === "CREATE"
      ? waitUntilStackCreateComplete
      : waitUntilStackUpdateComplete;
  // A new certificate waits for DNS validation inside the stack, and a new
  // distribution takes several minutes to deploy.
  await wait({ client: cfn, maxWaitTime: 3600 }, { StackName: name });
  return stack(name);
}

// The pitches stack's api function, table and games bucket.
function pitchesFrom(out) {
  if (!out.ApiUrl) return null;
  return {
    functionName: out.ApiFunctionName || null,
    url: out.ApiUrl,
    domain: new URL(out.ApiUrl).hostname,
    pushSecretArn: out.PushSecretArn || null,
    tableName: out.TableName || null,
    gamesBucket: out.GamesBucket || null,
  };
}

let pitches = pitchesFrom(outputs(await stack(config.stacks.pitches)));
const selected = named.length
  ? named
  : [
      ...(config.pitchesStack && pitches ? ["pitches"] : []),
      "site",
      "delivery",
    ];
if (selected.includes("pitches") && mode === "apply" && !config.pitchesStack)
  throw new Error(
    'infra/deployment.json has "pitchesStack": false: turn it on in a pull request before applying the pitches stack',
  );

let site = outputs(await stack(config.stacks.site));
let pagesKey = config.pages?.codeKey || null;
let reelKeys = config.reels
  ? { codeKey: config.reels.codeKey, layerKey: config.reels.layerKey }
  : null;
// The engines the reel function carries: every vendored one by major.minor, newest
// first ("0.7", later "0.8,0.7"), the same set tools/reels-bundle.mjs packages
// (docs/ENGINES.md). The pitches stack takes it from the site stack's ReelEngines output.
const reelEngines = reelEnginesOf();

// The pitches stack first: it needs only the site stack's code bucket and reel
// function, which are there already, and the site stack then takes its URL and table.
let apiKey = config.pitches?.codeKey || null;
if (selected.includes("pitches")) {
  if (!site.CodeBucket)
    throw new Error("The pitches stack waits for the site stack's code bucket");
  const fn = await bundleApi();
  apiKey = fn.key;
  console.log(`Api bundle ${fn.key} (${fn.zip.length} bytes)`);
  if (mode === "apply")
    await new S3Client(settings).send(
      new PutObjectCommand({
        Bucket: site.CodeBucket,
        Key: fn.key,
        Body: fn.zip,
        ContentType: "application/zip",
      }),
    );
  const reelsArn = site.ReelsFunctionArn || "";
  const out = outputs(
    await converge(
      config.stacks.pitches,
      "pitches",
      {
        CodeBucket: site.CodeBucket,
        ApiCodeKey: fn.key,
        // the reel function the site stack runs, or none; the engines it will render
        // once this run's site apply is done, else the ones it renders now
        ReelsFunctionArn: reelsArn,
        ReelEngines: !reelsArn
          ? ""
          : selected.includes("site") && config.reelRenderer
            ? reelEngines
            : site.ReelEngines || "",
      },
      ["CAPABILITY_IAM"],
    ),
  );
  pitches = pitchesFrom(out) || pitches;
}
// What the site stack points at: the pitches stack once it is on and there.
const cutover = Boolean(config.pitchesStack && pitches);
if (config.pitchesStack && !pitches && selected.includes("site"))
  console.log(
    'infra/deployment.json has "pitchesStack": true but the pitches stack is not there yet: the site runs no pitch pages or reels and gets no /api/* until pitches is applied, then site again',
  );

if (selected.includes("site")) {
  // The pages and reel functions read the pitches table: none until it is there.
  const table = cutover ? pitches.tableName || "" : "";
  if (table && site.CodeBucket) {
    const bundle = await bundlePages();
    pagesKey = bundle.key;
    console.log(`Pages bundle ${bundle.key} (${bundle.zip.length} bytes)`);
    if (mode === "apply")
      await new S3Client(settings).send(
        new PutObjectCommand({
          Bucket: site.CodeBucket,
          Key: bundle.key,
          Body: bundle.zip,
          ContentType: "application/zip",
        }),
      );
  }
  // The highlight reel function, only when deployment.json asks for it.
  reelKeys = null;
  if (config.reelRenderer && table && site.CodeBucket) {
    const fn = await bundleReels();
    const layer = await ffmpegLayer();
    reelKeys = { codeKey: fn.key, layerKey: layer.key };
    console.log(`Reels bundle ${fn.key} (${fn.zip.length} bytes)`);
    console.log(`Reels ffmpeg layer ${layer.key} (${layer.zip.length} bytes)`);
    if (mode === "apply")
      for (const b of [fn, layer])
        await new S3Client(settings).send(
          new PutObjectCommand({
            Bucket: site.CodeBucket,
            Key: b.key,
            Body: b.zip,
            ContentType: "application/zip",
          }),
        );
  }
  site = outputs(
    await converge(
      config.stacks.site,
      "site",
      {
        PagesCodeKey: table && site.CodeBucket ? pagesKey : "",
        PitchTable: table && site.CodeBucket ? table : "",
        ReelsCodeKey: reelKeys?.codeKey ?? "",
        ReelsLayerKey: reelKeys?.layerKey ?? "",
        ReelEngines: reelKeys ? reelEngines : "",
        ApiDomain: cutover ? pitches.domain : "",
      },
      ["CAPABILITY_IAM"],
    ),
  );
}

let delivery = outputs(await stack(config.stacks.delivery));
if (selected.includes("delivery")) {
  if (!site.DistributionId) {
    console.log("Plan only: the delivery stack waits for the site stack.");
    process.exit(0);
  }
  delivery = outputs(
    await converge(
      config.stacks.delivery,
      "delivery",
      {
        SiteBucket: site.SiteBucket,
        DistributionId: site.DistributionId,
        CodeBucket: site.CodeBucket,
        RepositoryId: config.githubRepositoryId || "",
        ApiFunctionName: cutover ? (pitches.functionName ?? "") : "",
      },
      ["CAPABILITY_IAM"],
    ),
  );
}

if (mode === "apply") {
  const next = {
    ...config,
    siteBucket: site.SiteBucket || null,
    codeBucket: site.CodeBucket || null,
    distributionId: site.DistributionId || null,
    cloudfrontDomain: site.DistributionDomain || null,
    certificateArn: site.CertificateArn || null,
    deploymentRoleArn: delivery.DeploymentRoleArn || null,
    pages: site.PagesEndpoint
      ? {
          codeKey: pagesKey,
          endpointDomain: site.PagesEndpoint,
          revisionId: site.PagesRevision || null,
        }
      : null,
    pitches: pitches ? { ...pitches, codeKey: apiKey } : null,
    reels: site.ReelsFunctionArn
      ? {
          functionArn: site.ReelsFunctionArn,
          engines: site.ReelEngines || null,
          ...reelKeys,
        }
      : null,
  };
  await fs.writeFile(
    "infra/deployment.json",
    JSON.stringify(next, null, 2) + "\n",
  );
  console.log("Wrote infra/deployment.json");
  if (delivery.DeploymentRoleArn)
    console.log(
      `GitHub repository variable AWS_DEPLOY_ROLE_ARN = ${delivery.DeploymentRoleArn}`,
    );
}
